"""Generate worked answers for the synthetic collection.

Runs a few illustrative strategies and deduplication rules over records.json
and writes answer-key.md. The strategies are deliberately simple models of
Boolean searching (title and abstract text, and assigned headings); they are
not any database's actual syntax.

Usage:
  python case-pack/synthetic/answer_key.py
"""

import difflib
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
RECORDS = json.loads((HERE / "records.json").read_text(encoding="utf-8"))["records"]
ELIGIBLE_STUDIES = sorted({r["study_id"] for r in RECORDS if r["study_eligible"]})
BY_ID = {r["id"]: r for r in RECORDS}


def text(record):
    return f"{record['title']} {record['abstract'] or ''}".lower()


def term(word):
    """Regex for a term; a trailing * truncates and spaces match a phrase."""
    stem = re.escape(word.lower().rstrip("*")).replace(r"\ ", r"[\s-]+")
    return re.compile(r"\b" + stem + (r"\w*" if word.endswith("*") else r"\b"))


def any_term(record, words):
    return any(term(w).search(text(record)) for w in words)


def heading(record, names):
    return any(h in names for h in record["headings"])


def in_sources(record, sources):
    return any(s in sources for s in record["sources"])


PEER = ["peer*", "cross-age", "classmate*", "buddies", "each other", "one another", "pals", "equals"]
TUTOR = ["tutor*", "coach*", "assisted learning"]
OUTCOME = ["comprehension", "understanding", "reading for meaning"]
DATABASES = {"Database A", "Database B"}


def narrow(r):
    return term("peer").search(text(r)) and term("tutor*").search(text(r)) and term("reading comprehension").search(text(r))


def broad(r):
    return any_term(r, PEER) and any_term(r, TUTOR) and any_term(r, OUTCOME)


def headings(r):
    return heading(r, {"Peer Tutoring", "Cross-Age Tutoring"}) and heading(r, {"Reading Comprehension"})


STRATEGIES = [
    (
        "A. Narrow free text, Database A only",
        "peer AND tutor* AND \"reading comprehension\" in title or abstract",
        lambda r: in_sources(r, {"Database A"}) and narrow(r),
    ),
    (
        "B. Broad free text, both databases",
        "(peer* OR cross-age OR classmate* OR buddies OR \"each other\" OR \"one another\" OR PALS OR equals) "
        "AND (tutor* OR coach* OR \"assisted learning\") AND (comprehension OR understanding OR \"reading for meaning\")",
        lambda r: in_sources(r, DATABASES) and broad(r),
    ),
    (
        "C. Headings only, both databases",
        "(Peer Tutoring OR Cross-Age Tutoring) AND Reading Comprehension, as assigned headings",
        lambda r: in_sources(r, DATABASES) and headings(r),
    ),
    (
        "D. B OR C, both databases",
        "free text or headings",
        lambda r: in_sources(r, DATABASES) and (broad(r) or headings(r)),
    ),
    (
        "E. D NOT \"secondary school*\"",
        "D, then remove records with secondary school* in title or abstract",
        lambda r: in_sources(r, DATABASES) and (broad(r) or headings(r)) and not term("secondary school*").search(text(r)),
    ),
    (
        "F. D plus the register and theses index",
        "D's logic applied to every source",
        lambda r: broad(r) or headings(r),
    ),
]


def normalise_title(title):
    return re.sub(r"[^a-z0-9 ]", "", title.lower().replace("randomized", "randomised").replace("-", " "))


def dedupe(records, threshold=None):
    """Return {record_id: kept_record_id}. DOI match always merges; with a
    threshold, normalised titles at or above that similarity also merge."""
    kept, mapping = [], {}
    for r in records:
        target = None
        for k in kept:
            if r["doi"] and r["doi"] == k["doi"]:
                target = k
            elif threshold is not None:
                ratio = difflib.SequenceMatcher(None, normalise_title(r["title"]), normalise_title(k["title"])).ratio()
                if ratio >= threshold:
                    target = k
            if target:
                break
        if target:
            mapping[r["id"]] = target["id"]
        else:
            kept.append(r)
            mapping[r["id"]] = r["id"]
    return mapping


def main():
    lines = [
        "# Answer key: synthetic collection",
        "",
        "Generated by `answer_key.py` from `records.json`. Do not edit by hand.",
        "",
        f"The collection has {len(RECORDS)} records and {len(ELIGIBLE_STUDIES)} eligible studies.",
        "",
        "## Strategies",
        "",
        "| Strategy | Records retrieved | Eligible studies found | Studies missed |",
        "|---|---|---|---|",
    ]
    details = []
    for name, logic, rule in STRATEGIES:
        hits = [r for r in RECORDS if rule(r)]
        found = sorted({r["study_id"] for r in hits if r["study_eligible"]})
        missed = [s for s in ELIGIBLE_STUDIES if s not in found]
        lines.append(f"| {name} | {len(hits)} | {len(found)} of {len(ELIGIBLE_STUDIES)} | {', '.join(missed) or 'none'} |")
        details.append(f"### {name}\n\nLogic: {logic}\n\nRetrieved: {', '.join(r['id'] for r in hits)}\n")
        for study in missed:
            reasons = [BY_ID[i]["planted"] for i in BY_ID if BY_ID[i]["study_id"] == study]
            details.append(f"- Missed {study}: {' / '.join(reasons)}")
        details.append("")
    lines += ["", *details]

    lines += [
        "## Deduplication",
        "",
        "Records from both databases, in record order, merged by DOI and optionally by title similarity.",
        "",
        "| Rule | Records left | Duplicate R002 merged | Eligible study lost by a wrong merge |",
        "|---|---|---|---|",
    ]
    pool = [r for r in RECORDS if in_sources(r, DATABASES)]
    for label, threshold in (("DOI only", None), ("DOI or title ≥ 0.95", 0.95), ("DOI or title ≥ 0.90", 0.90), ("DOI or title ≥ 0.80", 0.80)):
        mapping = dedupe(pool, threshold)
        remaining = {v for v in mapping.values()}
        wrong = sorted(
            {BY_ID[k]["study_id"] for k, v in mapping.items() if BY_ID[k]["study_id"] != BY_ID[v]["study_id"] and BY_ID[k]["study_eligible"]}
        )
        lines.append(
            f"| {label} | {len(remaining)} | {'yes' if mapping.get('R002') == 'R001' else 'no'} | {', '.join(wrong) or 'none'} |"
        )
    ratio = difflib.SequenceMatcher(None, normalise_title(BY_ID["R001"]["title"]), normalise_title(BY_ID["R013"]["title"])).ratio()
    lines += ["", f"Title similarity between R001 and R013 (different studies): {ratio:.3f}.", ""]

    (HERE / "answer-key.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[:20]))


if __name__ == "__main__":
    main()
