"""Can term mining repair the Moran strategy's title-and-abstract translation?

Chapter 7 uses this as a small worked example of the objective approach
(Hausner et al. 2012): split the known relevant records into a development
half and a validation half, mine the development half for words the
strategy misses, add the chosen words, and test the result on the
validation half, which played no part in choosing them.

Here the strategy is the Moran et al. (2021) strategy translated to title
and abstract (see field_checks.py), which loses 53 of the 137 included
records. The steps are:

1. Split the 137 included records at random (seed 7) into a development
   half of 69 and a validation half of 68.
2. For each block, take the development records that fail that block and
   list the words found in at least 20% of them and in at most 5% of the
   pool's records, ranked by the ratio of the two rates. The pool is the
   records the original search retrieved, not a random sample of the
   database, so the 5% ceiling is a rough stand-in for Hausner's
   population set.
3. Count how many of those development failures contain the block's own
   head word (behavio*, for the behaviour block) somewhere, which shows
   whether the block's proximity condition, rather than its vocabulary,
   is what fails.
4. Test the additions chosen from steps 2 and 3 (ADDITIONS, below) on
   both halves and on the whole pool.

The additions were chosen by reading the development records only:
conspecific* and competit* from step 2's risk list, behavio* from step 3,
and activ* from the development failures on the behaviour block, where
"active" is common but narrowly misses step 2's pool ceiling (step 2b
prints its counts). They are a judgement, as in Hausner's method, and
another searcher might choose differently.

Reads case-pack/cache/moran-2021/pool.csv and
case-pack/data/moran-2021/fields/ti-ab-only.csv. Writes
case-pack/data/moran-2021/fields/term-mining.md: words, counts and
identifiers only.

Usage:
  python case-pack/scripts/term_mining.py
"""

import collections
import csv
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import CACHE, DATA  # noqa: E402
from indexing_checks import Terms, words  # noqa: E402

SEED = 7
DEVELOPMENT = 69
MIN_IN_FAILURES = 0.20
MAX_IN_POOL = 0.05
MIN_LENGTH = 4
SHOWN = 15
OUTSIDE_THRESHOLDS = {"active": "behaviour"}

HEAD_WORDS = {"behaviour": Terms("behavio*"), "risk": Terms("risk*"), "condition": Terms("condition*")}

# Chosen by reading the development records only; see the module docstring.
ADDITIONS = {
    "behavio* anywhere (behaviour)": {"behaviour": Terms("behavio*")},
    "activ* (behaviour)": {"behaviour": Terms("activ*")},
    "conspecific*, competit* (risk)": {"risk": Terms("conspecific*", "competit*")},
}


def split(ids):
    """Shuffle in pool order with a fixed seed; the first DEVELOPMENT ids are the development half."""
    ids = list(ids)
    random.Random(SEED).shuffle(ids)
    return set(ids[:DEVELOPMENT]), set(ids[DEVELOPMENT:])


def mine(failures, tokens, pool_df, n_pool):
    """Words common in the failing records and rare in the pool."""
    df = collections.Counter()
    for i in failures:
        df.update(set(w for w in tokens[i] if w != "|"))
    n = len(failures)
    out = []
    for word, count in df.items():
        share, pool_share = count / n, pool_df[word] / n_pool
        if len(word) >= MIN_LENGTH and share >= MIN_IN_FAILURES and pool_share <= MAX_IN_POOL:
            out.append((share / pool_share, word, count, pool_share))
    out.sort(reverse=True)
    return out


def main():
    pool = list(csv.DictReader((CACHE / "moran-2021" / "pool.csv").open(encoding="utf-8")))
    flags = {r["id"]: r for r in csv.DictReader(
        (DATA / "moran-2021" / "fields" / "ti-ab-only.csv").open(encoding="utf-8"))}
    tokens = {r["id"]: words(r["title"]) + ["|"] + words(r["abstract"]) for r in pool}
    pool_df = collections.Counter()
    for t in tokens.values():
        pool_df.update(set(t))
    n_pool = len(pool)

    included = [r["id"] for r in pool if r["label_ft"] == "1"]
    dev, val = split(included)
    blocks = ("condition", "risk", "behaviour")

    lines = [
        "# Term mining on the Moran title-and-abstract translation",
        "",
        "Generated by `case-pack/scripts/term_mining.py`. Do not edit by hand.",
        "",
        f"Included records split at random (seed {SEED}): {len(dev)} development, {len(val)} validation.",
        "",
        "## Step 2: words common in the development failures and rare in the pool",
        "",
        f"Words of at least {MIN_LENGTH} letters in at least {MIN_IN_FAILURES:.0%} of the development records "
        f"that fail the block and in at most {MAX_IN_POOL:.0%} of the {n_pool:,} pool records, "
        f"top {SHOWN} by the ratio of the two rates.",
        "",
    ]
    for block in blocks:
        failures = [i for i in dev if flags[i][block] == "0"]
        mined = mine(failures, tokens, pool_df, n_pool)
        shown = ", ".join(f"{w} {c}/{len(failures)} (pool {p:.1%})" for _, w, c, p in mined[:SHOWN])
        lines.append(f"- **{block}** ({len(failures)} development failures): {shown or 'none'}")

    lines += ["", "## Step 2b: a word chosen outside the step 2 thresholds", ""]
    for word, block in OUTSIDE_THRESHOLDS.items():
        failures = [i for i in dev if flags[i][block] == "0"]
        count = sum(1 for i in failures if word in tokens[i])
        lines.append(f"- **{word}** ({block}): {count} of {len(failures)} development failures, "
                     f"{pool_df[word] / n_pool:.1%} of pool records")

    lines += ["", "## Step 3: failures that contain the block's head word elsewhere", ""]
    for block in blocks:
        failures = [i for i in dev if flags[i][block] == "0"]
        with_head = sum(1 for i in failures if HEAD_WORDS[block].spans(tokens[i]))
        lines.append(f"- **{block}**: {with_head} of {len(failures)}")

    base = {i: {b: flags[i][b] == "1" for b in blocks} for i in tokens}
    extra = {}
    for changes in ADDITIONS.values():
        for block, expr in changes.items():
            extra[(block, id(expr))] = {i: bool(expr.spans(t)) for i, t in tokens.items()}

    def admitted(i, chosen):
        ok = dict(base[i])
        for name in chosen:
            for block, expr in ADDITIONS[name].items():
                ok[block] = ok[block] or extra[(block, id(expr))][i]
        return all(ok.values())

    variants = [("Original, title and abstract", [])]
    variants += [(f"+ {name}", [name]) for name in ADDITIONS]
    variants += [("All three additions", list(ADDITIONS))]
    lines += [
        "",
        "## Step 4: the additions tested",
        "",
        "| Strategy | Development (of 69) | Validation (of 68) | Pool records retrieved |",
        "|---|---|---|---|",
    ]
    for label, chosen in variants:
        d = sum(admitted(i, chosen) for i in dev)
        v = sum(admitted(i, chosen) for i in val)
        p = sum(admitted(i, chosen) for i in tokens)
        lines.append(f"| {label} | {d} ({d / len(dev):.0%}) | {v} ({v / len(val):.0%}) | {p:,} |")

    out = DATA / "moran-2021" / "fields" / "term-mining.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
