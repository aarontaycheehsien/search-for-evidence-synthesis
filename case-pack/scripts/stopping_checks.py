"""Apply a statistical stopping criterion to the case pack's screening logs.

For each screening log (the Moran simulations and the CLEF 2019 runs on
CD010558), this script finds where Callaghan and Muller-Hansen's stopping
criterion would first allow screening to stop, and what would still be
unseen at that point. The criterion is computed with their package
buscarpy (version 0.0.2, MIT licence): calculate_h0 returns a p-value for
the null hypothesis that the recall target has not yet been reached, and
screening may stop when p falls below 1 minus the confidence level.

Settings: recall target 0.95 of title-and-abstract inclusions, confidence
0.95, unbiased urns (bias = 1, buscarpy's default and the conservative
choice). The test is evaluated after every CHECK_EVERY records, so a stop
is reported at the first checkpoint where p < 0.05; the true first record
can be up to CHECK_EVERY - 1 earlier.

The screening decision is the title-and-abstract label; the outcome that
matters to the review is how many full-text inclusions are still unseen.

Writes case-pack/data/stopping/statistical-stop.csv and summary.md.

Requires: buscarpy==0.0.2 (with numpy, scipy and pandas).

Usage:
  python case-pack/scripts/stopping_checks.py
"""

import csv
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import DATA  # noqa: E402

RECALL_TARGET = 0.95
ALPHA = 0.05
CHECK_EVERY = 5

MORAN_N = 4882
CLEF_N = 2815


def read_log(path, n_total):
    """Return (ta, ft) label lists in screening order, padded to n_total.

    Ranks missing from a log are irrelevant at both stages: the compact
    Moran logs list only starting records and title-and-abstract inclusions,
    and the single-run logs end once every inclusion has been found.
    """
    ta = [0] * n_total
    ft = [0] * n_total
    with open(path, encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            i = int(row["rank"]) - 1
            ta[i] = int(row["label_title_abstract"] or 0)
            ft[i] = int(row["label_full_text"] or 0)
    return ta, ft


def first_stop(ta, n_total, calculate_h0):
    """First checkpoint at which the criterion allows stopping, or None."""
    for n in range(CHECK_EVERY, n_total + 1, CHECK_EVERY):
        if sum(ta[:n]) == 0:
            continue
        if calculate_h0(ta[:n], n_total, recall_target=RECALL_TARGET) < ALPHA:
            return n
    return None


def outcome(name, group, ta, ft, n_total, calculate_h0):
    stop = first_stop(ta, n_total, calculate_h0)
    screened = stop if stop is not None else n_total
    return {
        "log": name,
        "group": group,
        "pool": n_total,
        "stop_at": stop if stop is not None else "",
        "share_screened": round(screened / n_total, 3),
        "ta_recall_at_stop": round(sum(ta[:screened]) / sum(ta), 3),
        "ft_unseen_at_stop": sum(ft) - sum(ft[:screened]),
        "ft_total": sum(ft),
    }


def describe(values):
    values = sorted(values)
    return f"{statistics.median(values):g} ({values[0]:g} to {values[-1]:g})"


def main():
    from buscarpy import calculate_h0

    rows = []
    seeds = DATA / "moran-2021" / "screening-seeds"
    for strategy in ("elas_u4", "tfidf_nb", "random"):
        for s in range(1, 11):
            ta, ft = read_log(seeds / f"{strategy}_s{s}.csv", MORAN_N)
            rows.append(outcome(f"{strategy}_s{s}", f"Moran {strategy}", ta, ft, MORAN_N, calculate_h0))
            print(rows[-1])
    for strategy in ("elas_u4", "tfidf_nb", "random"):
        ta, ft = read_log(DATA / "moran-2021" / "screening" / f"{strategy}.csv", MORAN_N)
        rows.append(outcome(strategy, "Moran single run", ta, ft, MORAN_N, calculate_h0))
        print(rows[-1])
    for run in ("sheffield_bm25_baseline", "padua_bm25_baseline", "padua_cal_p10_t1500"):
        ta, ft = read_log(DATA / "clef-2019" / "CD010558" / f"{run}.csv", CLEF_N)
        rows.append(outcome(run, "CD010558 CLEF run", ta, ft, CLEF_N, calculate_h0))
        print(rows[-1])

    out_dir = DATA / "stopping"
    out_dir.mkdir(parents=True, exist_ok=True)
    with (out_dir / "statistical-stop.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)

    lines = [
        "# Statistical stopping on the case pack's screening logs",
        "",
        "Generated by `case-pack/scripts/stopping_checks.py`. Do not edit by hand.",
        "",
        f"Criterion: buscarpy 0.0.2 `calculate_h0`, recall target {RECALL_TARGET}, stop when p < {ALPHA}, "
        f"checked every {CHECK_EVERY} records.",
        "",
        "## Moran pool, ten starting pairs per strategy (4,882 records, 137 full-text inclusions)",
        "",
        "| Strategy | Records screened at the stop | Share of the pool | Title-and-abstract recall at the stop | Full-text inclusions unseen |",
        "|---|---|---|---|---|",
    ]
    for strategy in ("elas_u4", "tfidf_nb", "random"):
        group = [r for r in rows if r["group"] == f"Moran {strategy}"]
        stops = [r["stop_at"] if r["stop_at"] != "" else MORAN_N for r in group]
        lines.append(
            f"| {strategy} | {describe(stops)} | {describe([r['share_screened'] for r in group])} | "
            f"{describe([r['ta_recall_at_stop'] for r in group])} | {describe([r['ft_unseen_at_stop'] for r in group])} |"
        )
    lines += ["", "Median (minimum to maximum) across ten runs.", "", "## Single runs", "",
              "| Log | Pool | Stop at | Share screened | Title-and-abstract recall | Full-text inclusions unseen (of total) |",
              "|---|---|---|---|---|---|"]
    for r in rows:
        if r["group"] in ("Moran single run", "CD010558 CLEF run"):
            lines.append(
                f"| {r['log']} | {r['pool']:,} | {r['stop_at'] or 'never'} | {r['share_screened']} | "
                f"{r['ta_recall_at_stop']} | {r['ft_unseen_at_stop']} (of {r['ft_total']}) |"
            )
    (out_dir / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
