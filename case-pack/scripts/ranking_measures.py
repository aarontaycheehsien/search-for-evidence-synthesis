"""Compute the ranked-list measures used in Appendix B on the CLEF runs.

For each of the three CLEF 2019 participant runs on CD010558, and for both
label sets (title-and-abstract inclusions and full-text inclusions), this
script computes the measures that Appendix B defines: average precision,
nDCG over the whole ranking with binary gains, the rank of the first and
last eligible record, the records screened to reach 95% recall, work saved
over sampling at 95% recall, and recall after screening 10% of the pool.

Definitions follow Appendix B:
- average precision: the mean, over eligible records, of the precision at
  each eligible record's rank;
- nDCG: the sum of 1 / log2(rank + 1) over eligible records, divided by
  the same sum for an ideal ranking that puts every eligible record first;
- 95% recall: the first rank at which at least ceil(0.95 * R) of the R
  eligible records have been seen;
- WSS@95: 0.95 minus the share of the pool screened to reach 95% recall
  (Cohen et al., 2006).

Reads case-pack/data/clef-2019/CD010558/*.csv (ranks and labels only).
Writes case-pack/data/clef-2019/CD010558/measures.md.

Usage:
  python case-pack/scripts/ranking_measures.py
"""

import csv
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import DATA  # noqa: E402

RUNS = {
    "sheffield_bm25_baseline": "Sheffield BM25",
    "padua_bm25_baseline": "Padua BM25",
    "padua_cal_p10_t1500": "Padua active learning",
}
LABELS = {"label_title_abstract": "title and abstract", "label_full_text": "full text"}


def measures(ranks, n_total):
    """Measures for a ranking, given the sorted ranks of the eligible records."""
    ranks = sorted(ranks)
    r = len(ranks)
    ap = sum((i + 1) / rank for i, rank in enumerate(ranks)) / r
    dcg = sum(1 / math.log2(rank + 1) for rank in ranks)
    ideal = sum(1 / math.log2(i + 2) for i in range(r))
    at95 = ranks[math.ceil(0.95 * r) - 1]
    tenth = round(0.1 * n_total)
    return {
        "eligible": r,
        "ap": ap,
        "ndcg": dcg / ideal,
        "first": ranks[0],
        "at95": at95,
        "wss95": 0.95 - at95 / n_total,
        "last": ranks[-1],
        "recall_10pct": sum(1 for rank in ranks if rank <= tenth) / r,
    }


def main():
    folder = DATA / "clef-2019" / "CD010558"
    lines = [
        "# Ranked-list measures for the CLEF 2019 runs on CD010558",
        "",
        "Generated by `case-pack/scripts/ranking_measures.py`. Do not edit by hand.",
        "",
    ]
    for label, label_name in LABELS.items():
        lines += [
            f"## Eligible records: {label_name} inclusions",
            "",
            "| Run | Eligible | Average precision | nDCG | First eligible at | 95% recall at | WSS@95 "
            "| Last eligible at | Recall after 10% of the pool |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for run, name in RUNS.items():
            rows = list(csv.DictReader((folder / f"{run}.csv").open(encoding="utf-8")))
            m = measures([int(row["rank"]) for row in rows if row[label] == "1"], len(rows))
            lines.append(
                f"| {name} | {m['eligible']} | {m['ap']:.3f} | {m['ndcg']:.3f} | {m['first']:,} "
                f"| {m['at95']:,} | {m['wss95']:.2f} | {m['last']:,} | {m['recall_10pct']:.2f} |"
            )
        lines.append("")
    lines.append(f"Pool: {len(rows):,} records.")
    (folder / "measures.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
