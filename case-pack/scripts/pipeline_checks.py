"""Which stages of a retrieval pipeline can add eligible records, and which only reorder them?

Chapter 6 uses this to separate three operations that products often
combine, on the Moran pool and its included records:

1. Reranking: the top 1,000 records of one ranking are reordered by another
   score. Records outside the 1,000 cannot come back.
2. Rank fusion: two complete rankings are merged by reciprocal rank fusion
   (score = sum over rankings of 1 / (60 + rank); Cormack et al., 2009).
3. Union of candidate sets: the top records of two routes are pooled, as a
   hybrid system does before it ranks.

The two routes are Chapter 4's BM25 ranking with the strategy's words
(lexical) and Chapter 5's dense ranking with the written question
(all-MiniLM-L6-v2). Both rank the same 4,882 records, which the authors'
Boolean searches had already admitted, so the figures show what each
operation can do within a fixed pool, not what any product would find in
its own index.

Reads case-pack/data/moran-2021/ranking/ranks.csv and
case-pack/data/moran-2021/representations/ranks.csv. Writes
case-pack/data/moran-2021/pipelines/summary.md.

Usage:
  python case-pack/scripts/pipeline_checks.py
"""

import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import DATA  # noqa: E402
from ranking_checks import ranks, recall_at  # noqa: E402

RRF_K = 60
CANDIDATES = 1000
CUTOFFS = (100, 250, 500, 1000, 2000)


def rerank(first, second, depth):
    """Keep the top `depth` of `first`, reorder them by `second`; others keep their order below."""
    inside = sorted((i for i, r in enumerate(first) if r <= depth), key=lambda i: second[i])
    outside = sorted((i for i, r in enumerate(first) if r > depth), key=lambda i: first[i])
    result = [0] * len(first)
    for position, i in enumerate(inside + outside, start=1):
        result[i] = position
    return result


def rrf(*rankings, k=RRF_K):
    scores = [sum(1 / (k + r[i]) for r in rankings) for i in range(len(rankings[0]))]
    return ranks(scores)


def union_top(a, b, depth):
    return {i for i, r in enumerate(a) if r <= depth} | {i for i, r in enumerate(b) if r <= depth}


def main():
    lexical_rows = list(csv.DictReader((DATA / "moran-2021" / "ranking" / "ranks.csv").open(encoding="utf-8")))
    dense_rows = {r["id"]: r for r in csv.DictReader(
        (DATA / "moran-2021" / "representations" / "ranks.csv").open(encoding="utf-8"))}
    ft = [int(r["label_ft"]) for r in lexical_rows]
    lexical = [int(r["rank_strategy_query"]) for r in lexical_rows]
    dense = [int(dense_rows[r["id"]]["rank_dense_question"]) for r in lexical_rows]
    n, total = len(ft), sum(ft)

    reranked = rerank(lexical, dense, CANDIDATES)
    fused = rrf(lexical, dense)
    columns = [("BM25, strategy words", lexical), ("Dense, question", dense),
               (f"BM25 top {CANDIDATES:,} reranked by dense", reranked), ("Reciprocal rank fusion", fused)]

    lines = [
        "# Reranking, fusion and union on the Moran pool",
        "",
        "Generated by `case-pack/scripts/pipeline_checks.py`. Do not edit by hand.",
        "",
        f"Pool: {n:,} records, {total} included after full text. Routes: BM25 with the strategy's words "
        "(Chapter 4) and dense similarity to the written question (Chapter 5).",
        "",
        "## Recall of included records within the top k",
        "",
        "| Records screened (top k) | " + " | ".join(name for name, _ in columns) + " |",
        "|---" * (len(columns) + 1) + "|",
    ]
    for k in CUTOFFS:
        lines.append(f"| {k:,} | " + " | ".join(f"{recall_at(r, ft, k):.2f}" for _, r in columns) + " |")

    lines += [
        "",
        f"Reranking the top {CANDIDATES:,} cannot change recall at {CANDIDATES:,}: "
        f"{recall_at(lexical, ft, CANDIDATES):.2f} before and {recall_at(reranked, ft, CANDIDATES):.2f} after.",
        "",
        "## Union of the two routes' candidates",
        "",
        "| Each route's top | Records in the union | Included records in the union | "
        "Included in the BM25 top only | Included in the dense top only | Included in both |",
        "|---|---|---|---|---|---|",
    ]
    for depth in (250, 500, 1000):
        pooled = union_top(lexical, dense, depth)
        a = {i for i, r in enumerate(lexical) if r <= depth and ft[i]}
        b = {i for i, r in enumerate(dense) if r <= depth and ft[i]}
        found = sum(ft[i] for i in pooled)
        lines.append(f"| {depth:,} | {len(pooled):,} | {found} of {total} ({found / total:.0%}) | "
                     f"{len(a - b)} | {len(b - a)} | {len(a & b)} |")
    lines += [
        "",
        "For comparison, screening the same number of records from either route alone:",
        "",
        "| Records screened | BM25, strategy words | Dense, question |",
        "|---|---|---|",
    ]
    for depth in (250, 500, 1000):
        size = len(union_top(lexical, dense, depth))
        lines.append(f"| {size:,} | {recall_at(lexical, ft, size):.2f} | {recall_at(dense, ft, size):.2f} |")

    out = DATA / "moran-2021" / "pipelines"
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
